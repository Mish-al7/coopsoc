export type TFn = (key: string, vars?: Record<string, string | number>) => string;

/** Unknown keys are returned as-is, so plain strings pass through safely. */
export function translator(lang: Lang): TFn {
  const d = DICT[lang] ?? ml;
  return (key, vars) => {
    let s: string = (d as Record<string, string>)[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export function toLang(v: string | undefined | null): Lang {
  return v === "en" ? "en" : "ml";
}

